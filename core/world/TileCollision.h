#pragma once

#include "core/math/TileVector2D.h"
#include "core/math/WorldVector2D.h"

namespace glimmer {
    class WorldContext;

    /**
     * Helper that queries the tile grid directly. This is the source of truth for the custom
     * tile-grid physics, replacing the Box2D static bodies previously generated by ChunkPhysicsHelper.
     * 直接查询瓦片网格的工具。这是自定义瓦片网格物理的唯一真相来源，取代了之前由 ChunkPhysicsHelper
     * 生成的 Box2D 静态体。
     */
    class TileCollision {
    public:
        /**
         * Whether the tile at the given tile coordinate is a solid (static) tile.
         * 给定瓦片坐标处的瓦片是否为实心（静态）瓦片。
         */
        [[nodiscard]] static bool IsSolidTile(const WorldContext *worldContext, const TileVector2D &tile);

        /**
         * Whether the segment a->b passes through at least one solid tile (digital differential
         * analyzer grid traversal). Used for line-of-sight checks, e.g. the item magnet.
         * 线段 a->b 是否穿过至少一个实心瓦片（DDA 网格遍历）。用于视线检测，例如物品磁铁。
         */
        [[nodiscard]] static bool LineHitsSolidTile(const WorldContext *worldContext,
                                                    const WorldVector2D &a, const WorldVector2D &b);
    };
}
